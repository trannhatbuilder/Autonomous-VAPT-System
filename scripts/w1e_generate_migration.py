# ---------- Topological sort by FK dependency ----------

def topo_sort_tables(metadata) -> list[str]:
    """Sort table names so that parents come before children (FK order)."""
    tables = list(metadata.tables.values())
    sorted_names: list[str] = []
    visited: set[str] = set()
    visiting: set[str] = set()

    def visit(table):
        if table.name in visited:
            return
        if table.name in visiting:
            # Circular FK — defer (SQLAlchemy will create with ALTER TABLE ADD CONSTRAINT)
            return
        visiting.add(table.name)
        for fk in table.foreign_keys:
            parent_table = fk.column.table
            if parent_table.name != table.name:  # skip self-references
                visit(parent_table)
        visiting.discard(table.name)
        visited.add(table.name)
        sorted_names.append(table.name)

    for t in tables:
        visit(t)

    # Add any tables not visited (shouldn't happen, but safety)
    for t in tables:
        if t.name not in visited:
            sorted_names.append(t.name)

    return sorted_names


# ---------- DDL generation ----------

def generate_table_ddl(table, dialect) -> str:
    """Generate CREATE TABLE DDL for a single table."""
    return str(CreateTable(table).compile(dialect=dialect))


def generate_index_ddl(table, dialect) -> list[str]:
    """Generate CREATE INDEX DDL for all indexes on a table."""
    stmts = []
    for index in table.indexes:
        stmts.append(str(CreateIndex(index).compile(dialect=dialect)))
    return stmts


