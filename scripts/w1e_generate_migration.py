def generate_migration():
    dialect = postgresql.dialect()
    metadata = Base.metadata

    table_names = topo_sort_tables(metadata)
    print(f"Table creation order ({len(table_names)} tables):")
    for i, name in enumerate(table_names, 1):
        print(f"  {i:2d}. {name}")

    # Generate CREATE TABLE statements
    upgrade_lines = []
    index_lines = []
    for name in table_names:
        table = metadata.tables[name]
        ddl = generate_table_ddl(table, dialect)
        # Format: op.execute('''<DDL>''')
        upgrade_lines.append(f"    op.execute('''")
        upgrade_lines.append(f"    {ddl}")
        upgrade_lines.append(f"    ''')")
        upgrade_lines.append("")

        # Indexes
        for idx_ddl in generate_index_ddl(table, dialect):
            index_lines.append(f"    op.execute('{idx_ddl}')")

    # Generate DROP TABLE statements (reverse order)
    downgrade_lines = []
    for name in reversed(table_names):
        downgrade_lines.append(f"    op.execute('DROP TABLE IF EXISTS {name} CASCADE')")

    # Table list for docstring
    table_list = "\n".join(f"    {i:2d}. {name}" for i, name in enumerate(table_names, 1))

    # Build migration file
    migration_content = MIGRATION_TEMPLATE.format(
        table_list=table_list,
        create_date=datetime.now().strftime("%Y-%m-%d"),
        upgrade_stmts="\n".join(upgrade_lines),
        index_stmts="\n".join(index_lines) if index_lines else "    # (no explicit indexes — all via column index=True)",
        downgrade_stmts="\n".join(downgrade_lines),
    )

    # Write file
    output_path = PROJECT_ROOT / "alembic" / "versions" / "0003_vapt_ai_baseline.py"
